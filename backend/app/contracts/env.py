    RAG_TOP_K = "RAG_TOP_K"
    CONFIDENCE_THRESHOLD = "CONFIDENCE_THRESHOLD"
    CRIT003_MODE = "CRIT003_MODE"
    CRIT005_MODE = "CRIT005_MODE"
    INSURANCE_MIN_SOURCE = "INSURANCE_MIN_SOURCE"
    HANDOFF_WAIT_SECONDS = "HANDOFF_WAIT_SECONDS"
    SESSION_TTL_MINUTES_WEB_CHAT = "SESSION_TTL_MINUTES_WEB_CHAT"
    SESSION_TTL_MINUTES_WHATSAPP = "SESSION_TTL_MINUTES_WHATSAPP"
    SESSION_TTL_MINUTES_PBX = "SESSION_TTL_MINUTES_PBX"
